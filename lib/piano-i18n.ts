export type Locale = 'vi' | 'en';

export function browserLocale(languages: readonly string[] = []): Locale {
  const primary = languages.find(l => l.trim()) ?? '';
  return /^vi(?:-|_|$)/i.test(primary) ? 'vi' : 'en';
}

